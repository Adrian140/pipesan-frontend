export const withMarkup = (amount) => Math.round(amount * (1 + SHIPPING_MARKUP) * 100) / 100;

export const findBand = (bands, weightKg) => {
  const index = bands.findIndex(([maxKg]) => weightKg <= maxKg);
  if (index === -1) return null;
  return { minKg: index === 0 ? 0 : bands[index - 1][0], maxKg: bands[index][0], cost: bands[index][1] };
};

export const getCountryBands = (country, serviceId) => {
  if (country.services) {
    const service = CHRONOPOST_SERVICES[serviceId] || CHRONOPOST_SERVICES[country.services[0]];
    return { service, bands: service.bands };
  }
  return { service: null, bands: CLASSIC_ZONE_BANDS[country.zone] };
};

// Customer price incl. VAT for one parcel, or null when the weight is not covered.
export const getShippingQuote = (countryCode, weightKg, serviceId) => {
  const country = SHIPPING_COUNTRIES.find((c) => c.code === countryCode);
  const weight = Number(weightKg);
  if (!country || !Number.isFinite(weight) || weight <= 0) return null;
  const { service, bands } = getCountryBands(country, serviceId);
  const band = findBand(bands, weight);
  if (!band) return { country, service, maxKg: bands[bands.length - 1][0], price: null };
  return {
    country,
    service,
    band,
    price: withMarkup(band.cost + (country.surcharge || 0))
  };
};
